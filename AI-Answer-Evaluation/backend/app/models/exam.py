"""SQLAlchemy models for Exams, Questions, Rubrics, Answer Keys, Study Materials, and Reference Answers."""

from datetime import datetime
from sqlalchemy import Boolean, Column, DateTime, ForeignKey, Integer, String, Text, Float, JSON
from sqlalchemy.orm import relationship

from app.database.session import Base


class Exam(Base):
    """Exam metadata model with KTU identification code and document attachments."""

    __tablename__ = "exams"

    id = Column(Integer, primary_key=True, index=True)
    exam_code = Column(String(100), unique=True, index=True, nullable=False)  # e.g. "KTU-CS301-MID1-A7K9"
    title = Column(String(255), nullable=False)
    subject = Column(String(100), nullable=False)  # Constitution of India, Industrial Economics, etc.
    subject_code = Column(String(50), nullable=True)  # CST 301, MCN 301, etc.
    semester = Column(String(50), nullable=True)
    academic_year = Column(String(50), nullable=True)
    exam_date = Column(String(50), nullable=True)
    exam_type = Column(String(100), default="Regular End-Semester")
    max_marks = Column(Float, nullable=False, default=100.0)
    duration_minutes = Column(Integer, default=180)
    instructions = Column(Text, nullable=True)

    # Document file attachments
    question_paper_path = Column(String(500), nullable=True)
    answer_key_path = Column(String(500), nullable=True)
    rubric_scheme_path = Column(String(500), nullable=True)

    status = Column(String(50), default="CONFIGURED")  # CONFIGURED, EVALUATING, COMPLETED
    teacher_id = Column(Integer, ForeignKey("users.id"), nullable=False)
    created_at = Column(DateTime, default=datetime.utcnow)

    # Relationships
    teacher = relationship("User", back_populates="exams")
    questions = relationship("Question", back_populates="exam", cascade="all, delete-orphan")
    study_materials = relationship("StudyMaterial", back_populates="exam", cascade="all, delete-orphan")
    answer_sheets = relationship("AnswerSheet", back_populates="exam", cascade="all, delete-orphan")
    analytics = relationship("Analytics", back_populates="exam", cascade="all, delete-orphan")


class Question(Base):
    """Question paper question / subquestion entity."""

    __tablename__ = "questions"

    id = Column(Integer, primary_key=True, index=True)
    exam_id = Column(Integer, ForeignKey("exams.id"), nullable=False)
    question_number = Column(String(50), nullable=False)  # e.g. "1(a)", "2(b)(i)"
    text = Column(Text, nullable=False)
    max_marks = Column(Float, nullable=False, default=10.0)
    subquestion_of = Column(String(50), nullable=True)

    # Relationships
    exam = relationship("Exam", back_populates="questions")
    answer_key = relationship("AnswerKey", back_populates="question", uselist=False, cascade="all, delete-orphan")
    rubric = relationship("Rubric", back_populates="question", uselist=False, cascade="all, delete-orphan")
    evaluations = relationship("Evaluation", back_populates="question")
    extracted_answers = relationship("ExtractedAnswer", back_populates="question")
    reference_proposals = relationship("ReferenceAnswerProposal", back_populates="question", cascade="all, delete-orphan")
    approved_reference = relationship("ApprovedReferenceAnswer", back_populates="question", uselist=False, cascade="all, delete-orphan")


class ReferenceAnswerProposal(Base):
    """Proposal generated by an LLM model for reference answer & rubric."""

    __tablename__ = "reference_answer_proposals"

    id = Column(Integer, primary_key=True, index=True)
    question_id = Column(Integer, ForeignKey("questions.id"), nullable=False)
    provider = Column(String(50), nullable=False)  # OLLAMA, GEMINI, CLAUDE, etc.
    model = Column(String(100), nullable=False)    # qwen3, gemma3, deepseek-r1:8b, etc.
    proposed_answer = Column(Text, nullable=False)
    proposed_rubric_json = Column(JSON, default=dict)
    key_concepts_json = Column(JSON, default=list)
    created_at = Column(DateTime, default=datetime.utcnow)

    # Relationships
    question = relationship("Question", back_populates="reference_proposals")


class ApprovedReferenceAnswer(Base):
    """Teacher-approved reference answer and rubric criteria."""

    __tablename__ = "approved_reference_answers"

    id = Column(Integer, primary_key=True, index=True)
    question_id = Column(Integer, ForeignKey("questions.id"), nullable=False, unique=True)
    approved_answer = Column(Text, nullable=False)
    approved_rubric_json = Column(JSON, default=dict)
    key_concepts_json = Column(JSON, default=list)
    version = Column(Integer, default=1)
    approved_by = Column(Integer, ForeignKey("users.id"), nullable=True)
    approved_at = Column(DateTime, default=datetime.utcnow)

    # Relationships
    question = relationship("Question", back_populates="approved_reference")


class AnswerKey(Base):
    """Answer key reference text and keywords per question."""

    __tablename__ = "answer_keys"

    id = Column(Integer, primary_key=True, index=True)
    question_id = Column(Integer, ForeignKey("questions.id"), nullable=False, unique=True)
    ideal_solution = Column(Text, nullable=False)
    keywords = Column(JSON, default=list)  # Key technical terms/concepts
    model_answer = Column(Text, nullable=True)

    # Relationships
    question = relationship("Question", back_populates="answer_key")


class Rubric(Base):
    """Evaluation rubric criteria and marking scheme per question."""

    __tablename__ = "rubrics"

    id = Column(Integer, primary_key=True, index=True)
    question_id = Column(Integer, ForeignKey("questions.id"), nullable=False, unique=True)
    criteria_json = Column(JSON, default=dict)  # {"concept": 40%, "keywords": 30%, "completeness": 30%}
    scoring_guidelines = Column(Text, nullable=True)

    # Relationships
    question = relationship("Question", back_populates="rubric")


class StudyMaterial(Base):
    """Uploaded study materials, textbook notes, and reference context."""

    __tablename__ = "study_materials"

    id = Column(Integer, primary_key=True, index=True)
    exam_id = Column(Integer, ForeignKey("exams.id"), nullable=False)
    title = Column(String(255), nullable=False)
    file_path = Column(String(500), nullable=False)
    content_type = Column(String(50), default="pdf")
    extracted_text = Column(Text, nullable=True)
    created_at = Column(DateTime, default=datetime.utcnow)

    # Relationships
    exam = relationship("Exam", back_populates="study_materials")
